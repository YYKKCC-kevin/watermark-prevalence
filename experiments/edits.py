"""Edit watermarked documents and rescore them.

Random edits (Model *-like):  for each doc draw eps_i ~ U[eps_lo, 1] (target EFFECTIVE retention), then
  scattered: replace each generated token independently with prob r = 1 - eps_i^{1/(h+1)}  (token + h-gram context intact w.p. ~eps_i)
  span:      replace contiguous spans (length ~ Geometric, mean 8) until a fraction 1-eps_i of generated tokens is replaced
Replacement tokens are drawn from the pool of tokens generated by the same model (unigram of other docs), so edits are
in-distribution tokens, not uniform vocabulary noise.  For every edited doc we record the realized retention
eps_eff = fraction of scored positions whose token AND h-gram context are all original.
Usage: CUDA_VISIBLE_DEVICES=2 python3 edits.py --npz data/gen/Qwen3-1p7B_gumbel.npz --mode scattered --eps_lo 0.3
"""
import argparse, os, numpy as np, torch
from wm import Watermarker, doc_pvalue

def edit_ids(ids, plen, eps, mode, pool, rng, h):
    ids = ids.copy(); g = ids[plen:]; L = len(g); edited = np.zeros(len(ids), bool)
    if mode == "scattered":
        r = 1 - eps ** (1.0 / (h + 1)); mask = rng.random(L) < r
    else:
        target = int(round((1 - eps) * L)); mask = np.zeros(L, bool)
        while mask.sum() < target:
            s = rng.integers(0, L); ln = rng.geometric(1 / 8.0); mask[s:min(L, s + ln)] = True
    idx = np.flatnonzero(mask)
    g[idx] = rng.choice(pool, size=len(idx)); ids[plen:] = g; edited[plen + idx] = True
    return ids, edited

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--npz", required=True); ap.add_argument("--mode", default="scattered", choices=["scattered", "span"])
    ap.add_argument("--eps_lo", type=float, default=0.3); ap.add_argument("--eps_hi", type=float, default=1.0); ap.add_argument("--seed", type=int, default=0)
    ap.add_argument("--max_new", type=int, default=0, help="if > 0, truncate each document to plen + U[50, max_new] generated tokens before editing (short-document pool)")
    a = ap.parse_args(); torch.set_grad_enabled(False)
    d = np.load(a.npz, allow_pickle=True); scheme = str(d["scheme"]); key = int(d["key"]); h = int(d["h"]); V = int(d["V"])
    ids_all, plen_all = d["ids"], d["prompt_len"]
    wm = Watermarker(scheme, key, V, h=h); rng = np.random.default_rng(a.seed)
    pool = np.concatenate([x[p:] for x, p in zip(ids_all, plen_all)])
    piv_out, pv_out, eps_nom, eps_eff, ns = [], [], [], [], []
    for k, (ids, plen) in enumerate(zip(ids_all, plen_all)):
        eps = rng.uniform(a.eps_lo, a.eps_hi)
        ids = np.asarray(ids, dtype=np.int64)
        if a.max_new > 0: ids = ids[: int(plen) + int(rng.integers(50, a.max_new + 1))]
        new, edited = edit_ids(ids, int(plen), eps, a.mode, pool, rng, h)
        piv, n, dup = wm.score(new, start=plen)
        # realized retention over scored positions (context + token original), computed with the same dedup rule
        seen = set(); intact = []; 
        for t in range(max(plen, h), len(new)):
            ctx = tuple(int(x) for x in new[t - h:t])
            if ctx in seen: continue
            seen.add(ctx)
            if new[t] >= V: continue
            intact.append(not edited[t - h:t + 1].any())
        piv_out.append(piv.astype(np.float32)); pv_out.append(doc_pvalue(piv, scheme, rng=rng)); eps_nom.append(eps); eps_eff.append(float(np.mean(intact)) if intact else np.nan); ns.append(n)
        if k % 500 == 0: print(k, flush=True)
    suffix = f"_edit_{a.mode}_eps{a.eps_lo}" + (f"-{a.eps_hi}" if a.eps_hi < 1 else "") + (f"_short{a.max_new}" if a.max_new > 0 else "")
    out = a.npz.replace(".npz", suffix + ".npz")
    np.savez(out, pivots=np.array(piv_out, dtype=object), pvals=np.array(pv_out), n=np.array(ns), eps_nominal=np.array(eps_nom), eps_eff=np.array(eps_eff), mode=a.mode)
    pv = np.array(pv_out); ee = np.array(eps_eff)
    print({"out": out, "docs": len(pv), "mean_eps_nominal": round(float(np.mean(eps_nom)), 3), "mean_eps_eff": round(float(np.nanmean(ee)), 3),
           "corr_nom_eff": round(float(np.corrcoef(eps_nom, np.nan_to_num(ee))[0, 1]), 3), "frac_p_le_0.05": round(float((pv <= 0.05).mean()), 3), "median_n": float(np.median(ns))})

if __name__ == "__main__":
    main()
